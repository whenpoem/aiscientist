"""Agent-host setup helpers for Claude Code and Codex.

The research core is host-neutral: MCP servers, hooks, and the cockpit all
cooperate through the same SQLite state file. This module owns only the thin
project-local configuration layer that lets a user choose Claude Code, Codex,
or both during setup.
"""

